"""Audited two-stage Dodec assembly deck; no artificial pipe restraints."""
from __future__ import annotations
import json
from pathlib import Path
import numpy as np

from .loads import consistent_surface_force, cload_text, projected_patch_area
from .mesh import SolidMesh
from .project import StructuralProject, write_json
from .workflow import verify_evidence


def set_text(name, nodes):
    ids = list(map(int, nodes))
    if not ids:
        raise ValueError(f"Empty node selection {name}")
    return f"*NSET,NSET={name}\n" + "\n".join(",".join(map(str,ids[i:i+16])) for i in range(0,len(ids),16))+"\n"


def required_mesh_selections(mesh: SolidMesh):
    for name in ("pipe","hub","screw_1","screw_2","screw_3"):
        if not mesh.element_sets.get(name):
            raise ValueError(f"Missing assembly component: {name}")
    for name in ("midpoint","load_patch","pipe_bore","hub_snout", *[
            f"screw_{i}_{kind}" for i in range(1,4) for kind in ("anchor","cone","seat","cut")],
            *[f"hub_hole_{i}" for i in range(1,4)]):
        if not mesh.surfaces.get(name):
            raise ValueError(f"Missing assembly surface: {name}")


def bind_mesh_evidence(project: StructuralProject, mesh: SolidMesh, *, backend_fixture_report: dict):
    """Return project with mesh-derived bindings after geometric verification.

    No pass is inferred from merely creating a mesh. Explicit preparation
    evidence generated by the mesher is required for cut/contact checks.
    """
    import copy
    from dataclasses import asdict
    from .backends.calculix import DEFAULT_EXECUTABLE
    from .backends.feasibility import verify_backend_feasibility
    from .project import sha256
    project = copy.deepcopy(project)
    if project.contacts.friction_coefficient > 0:
        from .backends.friction_qualification import verify_friction_qualification
        friction_verification = verify_friction_qualification(project)
        # An explicit reference is never replaced. The bundled reference is
        # bound only after it has actually passed (the current proof has not).
        project.solver.setdefault("friction_qualification_manifest",friction_verification["qualification_manifest"])
        project.preparation["friction_qualification_verification"] = friction_verification
    variant = project.solver.get("variant", "serial")
    if variant not in {"serial", "multithread"}:
        raise ValueError(f"Unverified CalculiX solver variant: {variant}")
    executable = DEFAULT_EXECUTABLE.with_name("ccx_MT.exe") if variant == "multithread" else DEFAULT_EXECUTABLE
    backend_verification = verify_backend_feasibility(
        backend_fixture_report, executable, expected_version=project.solver.get("expected_version", "2.23"))
    required_mesh_selections(mesh)
    if mesh.provenance.get("source_sha256") != project.source_sha256:
        raise ValueError("Mesh source revision does not match project")
    if mesh.provenance.get("coordinate_frame") != "comsol_reference_mm":
        raise ValueError("Assembly mesh must be in the verified COMSOL reference frame")
    manifest_path = Path(mesh.provenance.get("mesh_manifest", ""))
    if not manifest_path.is_file():
        raise ValueError("Mesh generation manifest is required to bind actual settings")
    mesh_manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if mesh_manifest.get("source_sha256") != project.source_sha256:
        raise ValueError("Mesh generation manifest source revision does not match project")
    counts = mesh_manifest.get("counts", {})
    if counts.get("nodes") != len(mesh.node_ids) or counts.get("elements") != len(mesh.element_ids):
        raise ValueError("Mesh generation manifest counts do not match the supplied mesh")
    quality = mesh_manifest.get("mesh_quality", {})
    minimum_jacobian = quality.get("min_scaled_jacobian")
    if (isinstance(minimum_jacobian, bool) or not isinstance(minimum_jacobian, (int, float))
            or not np.isfinite(minimum_jacobian) or minimum_jacobian < .1
            or quality.get("nonpositive_elements") != 0):
        raise ValueError("Assembly mesh requires a finite native minimum scaled Jacobian >= 0.1 and zero nonpositive elements")
    from .geometry_revision import verify_mesh_geometry_revision
    geometry_verification = verify_mesh_geometry_revision(project, mesh, mesh_manifest)
    if project.geometry_revision:
        project.preparation["geometry_revision_verification"] = geometry_verification
    project.preparation["mesh_quality_binding"] = {
        "minimum_scaled_jacobian": minimum_jacobian,
        "required_minimum_scaled_jacobian": .1,
        "nonpositive_elements": quality["nonpositive_elements"],
        "passed": True,
        "manifest":{"path":str(manifest_path.resolve()), "sha256":sha256(manifest_path)},
        "scope":"Native high-order quality of the generated assembly mesh; does not establish mesh convergence."}
    settings = mesh_manifest.get("settings", {})
    requested_settings = asdict(project.mesh)
    if requested_settings.get("slot_size_mm") is None:
        requested_settings.pop("slot_size_mm", None)
    setting_map = {"global_size_mm":"far_size_mm", "contact_size_mm":"contact_size_mm",
                   "thickness_size_mm":"thickness_size_mm", "element_order":"order", "threads":"threads"}
    for project_key, manifest_key in setting_map.items():
        if manifest_key not in settings:
            raise ValueError(f"Actual mesh generation setting missing: {manifest_key}")
        setattr(project.mesh, project_key, settings[manifest_key])
    project.mesh.bore_snout_size_mm=settings.get("bore_snout_size_mm")
    setting_map["bore_snout_size_mm"]="bore_snout_size_mm"
    project.mesh.slot_size_mm=settings.get("slot_size_mm")
    setting_map["slot_size_mm"]="slot_size_mm"
    actual_settings = asdict(project.mesh)
    if actual_settings.get("slot_size_mm") is None:
        actual_settings.pop("slot_size_mm", None)
    project.preparation["mesh_settings_binding"] = {
        "manifest":{"path":str(manifest_path.resolve()), "sha256":sha256(manifest_path)},
        "requested":requested_settings, "actual":actual_settings,
        "changes":{key:{"requested":requested_settings.get(key), "actual":actual_settings.get(key)}
                   for key in setting_map if requested_settings.get(key) != actual_settings.get(key)},
        "generation_settings":settings,
        "node_budget_policy":"Project max_nodes remains the requested solve limit; the mesh generator's separate limit is recorded in generation_settings."}
    for name, ids in mesh.element_sets.items():
        project.selections[name] = {"kind":"elements", "count":len(ids)}
        if name.startswith("screw_"):
            project.selections[name+"_body"] = project.selections[name]
    for name, faces in mesh.surfaces.items():
        project.selections[name] = {"kind":"element_faces", "count":len(faces)}
    for key in ("cuts_verified","contact_clearances_verified"):
        project.preparation[key] = mesh.provenance.get(key) is True
    project.preparation["backend_fixtures_passed"] = backend_verification["verified"]
    project.preparation["backend_fixture_evidence"] = backend_fixture_report
    project.preparation["backend_fixture_verification"] = backend_verification
    project.validate()
    return project


def write_assembly_deck(project: StructuralProject, mesh: SolidMesh, path: Path) -> dict:
    project.validate(verify_source=True)
    friction_verification = None
    if project.contacts.friction_coefficient > 0:
        from .backends.friction_qualification import verify_friction_qualification
        friction_verification = verify_friction_qualification(project)
    mesh.validate()
    required_mesh_selections(mesh)
    issues = verify_evidence(project) + project.readiness_issues()
    if issues:
        raise ValueError("Assembly preparation incomplete:\n" + "\n".join(issues))
    if mesh.provenance.get("source_sha256") != project.source_sha256 or mesh.provenance.get("coordinate_frame") != "comsol_reference_mm":
        raise ValueError("Mesh identity/frame mismatch")
    from .geometry_revision import verify_mesh_geometry_revision
    from .mesh import mesh_fingerprint
    mesh_manifest = json.loads(Path(mesh.provenance["mesh_manifest"]).read_text(encoding="utf-8"))
    geometry_verification = verify_mesh_geometry_revision(project, mesh, mesh_manifest)
    prepared_mesh_fingerprint = mesh_fingerprint(mesh)
    if mesh.provenance.get("patch_width_mm") != project.loads.patch_width_mm:
        raise ValueError("Load footprint differs between mesh and project")
    patch_nodes=mesh.surface_nodes("load_patch")
    patch_points=mesh.points_mm[[mesh._nodes[node] for node in patch_nodes]]
    if (np.max(np.abs(patch_points[:,0]))>project.loads.patch_width_mm/2+1e-4
            or np.max(patch_points[:,1])>=0 or np.max(patch_points[:,2])>1e-4
            or np.min(patch_points[:,2]) < -project.loads.patch_axial_length_mm-1e-4):
        raise ValueError("Load patch nodes do not lie in the verified -Y projected footprint")
    if len(mesh.node_ids) > project.mesh.max_nodes:
        raise ValueError("Pilot mesh exceeds configured node budget; inspect resource estimate first")
    from .backends.explicit_pretension import explicit_pretension
    reference_nodes=[int(mesh.node_ids.max())+i for i in range(1,4)]
    equations=[]
    cut_maps={}
    for i,ref in enumerate(reference_nodes,1):
        head_ids=mesh.provenance.get("pretension_head_element_sets",{}).get(str(i))
        if not head_ids:
            raise ValueError(f"Complete head-side element selection missing for screw {i}")
        axis=mesh.provenance["pretension_axes_reference"][str(i)]
        mesh,eq,node_map=explicit_pretension(mesh,f"screw_{i}_cut",head_ids,axis,ref,reserved_node_ids=reference_nodes)
        equations.append(eq)
        cut_maps[str(i)]={str(k):v for k,v in node_map.items()}
    mesh.validate()
    # Uniform direction is fixed in the registered reference frame.
    force = project.loads.service_force_n*np.asarray(project.loads.direction_reference)
    forces, load_report = consistent_surface_force(mesh,"load_patch",force)
    expected_area = projected_patch_area(project.pipe_od_mm/2,project.loads.patch_width_mm,project.loads.patch_axial_length_mm)
    load_report["analytic_curved_area_mm2"] = expected_area
    load_report["area_relative_error"] = abs(load_report["area_mm2"]-expected_area)/expected_area
    if load_report["area_relative_error"] > .005:
        raise ValueError("Load patch mesh area differs by more than 0.5% from the specified projected footprint")
    midpoint = mesh.surface_nodes("midpoint")
    if np.max(np.abs(mesh.points_mm[[mesh._nodes[n] for n in midpoint],2])) > 1e-5:
        raise ValueError("Midpoint surface is not on registered Z=0; refusing global Uz constraint")
    hub_nodes = sorted({int(n) for e in mesh.element_sets["hub"] for n in mesh.tetra10[mesh._elements[e]]})
    if set(hub_nodes) & set(midpoint):
        raise ValueError("Hub and pipe improperly share nodes")
    for a,b in (("pipe","hub"),("pipe","screw_1"),("pipe","screw_2"),("pipe","screw_3")):
        ids_a={int(n) for e in mesh.element_sets[a] for n in mesh.tetra10[mesh._elements[e]]}
        ids_b={int(n) for e in mesh.element_sets[b] for n in mesh.tetra10[mesh._elements[e]]}
        if ids_a & ids_b:
            raise ValueError(f"Opening interface {a}/{b} shares nodes")
    text = "*HEADING\nDodec half-pipe: whole-screw preload then retained adjustment and service load; N-mm-MPa\n"
    text += mesh.deck_geometry()
    text += set_text("HUB_FIXED",hub_nodes) + set_text("MIDPOINT_SYMMETRY",midpoint)
    rigid_anchorage_nodes={str(i):mesh.surface_nodes(f"screw_{i}_anchor") for i in range(1,4)}
    duplicated_head_nodes={n for mapping in cut_maps.values() for n in mapping.values()}
    for i in range(1,4):
        nodes=rigid_anchorage_nodes[str(i)]
        if duplicated_head_nodes.intersection(nodes):
            raise ValueError("Anchorage incorrectly includes a duplicated head-side cut node")
        text+=set_text(f"RIGID_ANCHORAGE_{i}",nodes)
    pretension = []
    for i in range(1,4):
        ref = reference_nodes[i-1]
        text += f"*NODE,NSET=PRETENSION_BOLT_{i}\n{ref},0,0,0\n"
        axis = np.asarray(mesh.provenance["pretension_axes_reference"][str(i)],dtype=float)
        if not np.isclose(np.linalg.norm(axis),1,atol=1e-8):
            raise ValueError("Pretension cut axis must be normalized")
        pretension.append({"screw":i,"reference_node":ref,"node_set":f"PRETENSION_BOLT_{i}","axis":axis.tolist(),"target_n":project.loads.screw_preloads_n[i-1]})
    text += "".join(equations)
    for name,mat,sets in (("PIPE_MATERIAL",project.pipe,["PIPE"]),("SCREW_MATERIAL",project.screw,["SCREW_1","SCREW_2","SCREW_3","HUB"])):
        text+=f"*MATERIAL,NAME={name}\n*ELASTIC\n{mat.youngs_modulus_mpa:.14g},{mat.poisson_ratio:.14g}\n"
        for elset in sets:
            text+=f"*SOLID SECTION,ELSET={elset},MATERIAL={name}\n"
    text+="*BOUNDARY\nHUB_FIXED,1,3\nMIDPOINT_SYMMETRY,3,3\n"
    for i in range(1,4):
        # Exact elimination of u_slave = u_master for the prescribed fixed hub.
        # Only the audited, physically overlapping cylinder surface is included.
        text+=f"RIGID_ANCHORAGE_{i},1,3\n"
    pairs = [("PIPE_BORE","HUB_SNOUT")]+[(f"SCREW_{i}_SEAT",f"SCREW_{i}_CONE") for i in range(1,4)]
    for slave,master in pairs:
        text+=f"*CONTACT PAIR,INTERACTION=SEPARATING_CONTACT,TYPE=SURFACE TO SURFACE\n{slave},{master}\n"
    text+="*SURFACE INTERACTION,NAME=SEPARATING_CONTACT\n*SURFACE BEHAVIOR,PRESSURE-OVERCLOSURE=LINEAR\n"
    text+=f"{project.contacts.normal_stiffness_mpa_per_mm:.14g}\n"
    if project.contacts.friction_coefficient > 0:
        # Coulomb slope must remain explicit and held fixed in sensitivity studies.
        text+=f"*FRICTION\n{project.contacts.friction_coefficient:.14g},{project.contacts.normal_stiffness_mpa_per_mm/10:.14g}\n"
    # CalculiX shares FREQUENCY across all FILE/PRINT requests. The last value
    # governs nodal, element and contact output alike; final step states are
    # always written. Scalar force/contact histories therefore also have only
    # final stage states, while STA/CVG retain the complete increment history.
    outputs="*NODE FILE,GLOBAL=YES,FREQUENCY=1000000\nU,RF\n*EL FILE\nS\n*NODE PRINT,NSET=ALL_NODES,GLOBAL=YES\nU,RF\n*EL PRINT,ELSET=ALL_ELEMENTS\nS\n"
    for item in pretension:
        outputs+=f"*NODE PRINT,NSET={item['node_set']},GLOBAL=YES\nU,RF\n"
    outputs+="*CONTACT FILE\nCDIS,CSTR\n*CONTACT PRINT\nCDIS,CSTR\n"
    for slave,master in pairs:
        outputs+=f"*CONTACT PRINT,SLAVE={slave},MASTER={master}\nCF,CFN\n"
    step_controls=project.static_step_controls()
    from .backends.contact_controls import contact_control_cards, verify_contact_control_binding
    contact_controls=contact_control_cards(project)
    def static_line(stage):
        values=step_controls[stage]
        return f"{values['initial_increment']:.14g},1.,{values['minimum_increment']:.14g},{values['maximum_increment']:.14g}\n"
    text+="*STEP,NLGEOM,INC=500\n"+contact_controls+"*STATIC\n"+static_line("preload")+"*CLOAD\n"
    for item in pretension:
        text+=f"{item['reference_node']},1,{item['target_n']:.14g}\n"
    text+=outputs+"*END STEP\n"
    text+="*STEP,NLGEOM,INC=1000\n"+contact_controls+"*STATIC\n"+static_line("service")+"*CLOAD,OP=NEW\n*BOUNDARY,FIXED\n"
    for item in pretension:
        text+=f"{item['reference_node']},1,1\n"
    text+=cload_text(forces)+outputs+"*END STEP\n"
    path=Path(path)
    if path.exists():
        raise FileExistsError("Refusing to overwrite an assembly deck")
    path.parent.mkdir(parents=True,exist_ok=True)
    mesh.save(path.parent/"solver-mesh.npz")
    path.write_text(text,encoding="utf-8")
    manifest={"project_fingerprint":project.fingerprint(),"coordinate_frame":"comsol_reference_mm",
              "prepared_mesh_fingerprint":prepared_mesh_fingerprint,
              "solver_mesh_fingerprint":mesh_fingerprint(mesh),
              "geometry_revision":project.geometry_revision,
              "geometry_revision_verification":geometry_verification,
              "pretension":pretension,"load":load_report,"contact_pairs":[{"slave":s,"master":m} for s,m in pairs],
              "pretension_formulation":"explicit paired-node axial jump with scalar work-conjugate force",
              "pretension_cut_node_maps":cut_maps,"solver_mesh":"solver-mesh.npz",
              "anchorage_enforcement":"fixed_master_elimination",
              "rigid_anchorage_nodes":rigid_anchorage_nodes,
              "anchorage_pair_mapping":[{"slave":f"SCREW_{i}_ANCHOR","master":f"HUB_HOLE_{i}","master_displacement_mm":[0,0,0]} for i in range(1,4)],
              "hub_fixed_nodes":hub_nodes,"midpoint_nodes":midpoint,"hub_node_set":"HUB_FIXED","midpoint_node_set":"MIDPOINT_SYMMETRY",
              "applied_nodal_forces":{str(n):f.tolist() for n,f in forces.items()},
              "final_artificial_supports":[],"fixed_hub_stress":"undefined_for_physical_interpretation",
              "stages":["100 percent specified per-screw preload, zero patch load","retained tightening, ramp specified-direction patch force"],
              "expected_step_times":[1.,1.],"model_preparation_verified":True,
              "step_controls":step_controls,"adaptive_increment_cutbacks":True,
              "output_frequency":1000000,"field_history":"final state of each step only",
              "scalar_force_contact_history":"final state of each step only (CalculiX global FREQUENCY)",
              "increment_convergence_history":"complete STA/CVG and stdout retained",
              "screw_forces_free_to_redistribute":True,"contact_initial_adjustment":"none",
              "contact_clearances_verified":mesh.provenance.get("contact_clearances_verified") is True,
              "comparison_classification":project.registration.get("comparison_classification")}
    if project.contact_count_relative_tolerance() is not None:
        manifest["contact_count_relative_tolerance"]=project.contact_count_relative_tolerance()
        contact_binding=verify_contact_control_binding(project,text,manifest)
        if not contact_binding["verified"]:
            raise ValueError("Generated contact controls do not match their declared numerical setting")
        manifest["contact_controls_binding"]=contact_binding
    if friction_verification is not None:
        manifest.update(friction_coefficient=project.contacts.friction_coefficient,
                        normal_contact_stiffness_mpa_per_mm=project.contacts.normal_stiffness_mpa_per_mm,
                        friction_stick_slope_mpa_per_mm=project.contacts.normal_stiffness_mpa_per_mm/10,
                        friction_qualification_verification=friction_verification)
    write_json(path.with_suffix(".assembly.json"),manifest)
    return manifest
